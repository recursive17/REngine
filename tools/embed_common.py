"""Общая часть для embed-скриптов: превращает любой файл в пару .h/.cpp
с массивом байт (extern) и функцией, которая возвращает std::span.

Сами скрипты: embed_image.py и embed_audio.py.
"""

import re
from pathlib import Path

BYTES_PER_LINE = 16
# После этого размера предупреждаем: огромный массив сильно тормозит компиляцию
WARN_SIZE = 2 * 1024 * 1024


def to_identifier(stem: str) -> str:
    """'my-logo 2' -> 'my_logo_2' (валидное имя для C++)."""
    ident = re.sub(r"\W", "_", stem)
    if ident[0].isdigit():
        ident = "_" + ident
    return ident


def to_function_name(ident: str, ext: str) -> str:
    """'my_logo' + 'png' -> 'myLogoPng'."""
    parts = [p for p in ident.split("_") if p] + [ext]
    return parts[0].lower() + "".join(p.capitalize() for p in parts[1:])


def embed(src: Path, out_dir: Path, name: str | None, allowed_ext: set[str], kind: str) -> None:
    if not src.is_file():
        raise SystemExit(f"[{kind}] файл не найден: {src}")

    ext = src.suffix.lower().lstrip(".")
    if ext not in allowed_ext:
        raise SystemExit(f"[{kind}] неподдерживаемый формат .{ext}, можно: "
                         + ", ".join(sorted(allowed_ext)))

    data = src.read_bytes()
    if len(data) > WARN_SIZE:
        print(f"[{kind}] ВНИМАНИЕ: файл {len(data) / 1024 / 1024:.1f} МБ. "
              "Такой массив будет долго компилироваться, лучше грузить с диска.")

    ident = to_identifier(name or src.stem)
    func = to_function_name(ident, ext)
    array = f"{ident}_{ext}_data"

    out_dir.mkdir(parents=True, exist_ok=True)
    header = out_dir / f"{ident}.h"
    source = out_dir / f"{ident}.cpp"

    header.write_text(
        "#pragma once\n"
        "#include <span>\n\n"
        f"// Generated by tools/embed_{kind}.py from {src.name} - do not edit by hand\n"
        "namespace re::assets {\n"
        f"    std::span<const unsigned char> {func}();\n"
        "}\n",
        encoding="utf-8",
    )

    lines = []
    for i in range(0, len(data), BYTES_PER_LINE):
        chunk = data[i:i + BYTES_PER_LINE]
        lines.append("        " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")

    source.write_text(
        f'#include "{header.name}"\n\n'
        "namespace re::assets {\n"
        f"    // {src.name}, {len(data)} bytes\n"
        f"    extern const unsigned char {array}[] = {{\n"
        + "\n".join(lines) + "\n"
        "    };\n\n"
        f"    std::span<const unsigned char> {func}() {{\n"
        f"        return {{ {array}, sizeof({array}) }};\n"
        "    }\n"
        "}\n",
        encoding="utf-8",
    )

    print(f"[{kind}] {src.name} ({len(data)} байт) -> {header} , {source}")
    print(f"[{kind}] функция: re::assets::{func}()")
    print(f"[{kind}] не забудь добавить {source.name} в add_executable в REngine/CMakeLists.txt")
